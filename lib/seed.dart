Future<void> seedDatabase(Database db) async {
  final ids = <String, int>{};
  for (final (name, muscle) in seedExercises) {
    ids[name] = await db.insert('exercise', {'name': name, 'muscle': muscle});
  }
  await addMissingFoods(db);
  for (final (name, items) in seedRoutines) {
    final rid = await db.insert('routine', {'name': name});
    var pos = 0;
    for (final (ex, sets, lo, hi) in items) {
      await db.insert('routine_exercise', {
        'routine_id': rid,
        'exercise_id': ids[ex]!,
        'position': pos++,
        'sets': sets,
        'rep_min': lo,
        'rep_max': hi,
      });
    }
  }
}

/// Adds any built-in foods the phone doesn't have yet (used on first install and on updates).
Future<int> addMissingFoods(Database db) async {
  final rows = await db.query('food', columns: ['name']);
  final have = {for (final r in rows) (r['name'] as String).toLowerCase()};
  var added = 0;
  for (final f in [...seedFoods, ...extraFoods]) {
    if (have.contains(f.$1.toLowerCase())) continue;
    await db.insert('food', {
      'name': f.$1,
      'kcal': f.$2,
      'protein': f.$3,
      'carbs': f.$4,
      'fat': f.$5,
      'serving_g': f.$6,
      'source': 'builtin',
    });
    have.add(f.$1.toLowerCase());
    added++;
  }
  return added;
}
